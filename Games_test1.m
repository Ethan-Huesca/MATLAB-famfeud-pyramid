%function to generate random list of numbers with two limits
function [zrandomm] = generaterandomlist(x, y)
    zrandomm = zeros(x,1);              %Create array in which integers will be placed
    xrandom = randi([y x]);            %generate first random number
    zrandomm(1,1) = xrandom;             %save it on the first element of the array
    for ii=2:x
        pause(0.1)                      %pause
        contrand = 0;                   %counter to tell if new rand ~= all the others
        flagrand=1;                     %flag to enter infinite cycle 
        xrandom = randi([y x]);        %generate random num between 1 and 4 
    
        %infinite cycle to generate rand num which doesnt repeat
        while flagrand==1
            pause(0.1);                     %Pause
            for xx=ii:-1:2                  %for cycle to compare current value with all the others
                if xrandom~=zrandomm(xx-1,1) %if current value different from previous value
                    contrand=contrand+1;    %add one to counter
                end
            end
            if contrand==(ii-1)             %if counter equals the amount of previous values
                zrandomm(ii,1)=xrandom;
                flagrand = 0;
            else
                xrandom = randi([y x]);
                contrand = 0;
            end    
        end
    end
    zrandomm
end

